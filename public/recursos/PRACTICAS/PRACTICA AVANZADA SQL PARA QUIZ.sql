WITH jerarquia (EMPLOYEE_ID,LAST_NAME,MANAGER_ID,NIVEL) AS (
SELECT EMPLOYEE_ID,
        LAST_NAME,
        MANAGER_ID,
        1
FROM HR.EMPLOYEES
WHERE MANAGER_ID IS NULL
UNION ALL
SELECT E.EMPLOYEE_ID,
        E.LAST_NAME,
        E.MANAGER_ID,
        J.NIVEL + 1
FROM HR.EMPLOYEES E
JOIN jerarquia J ON E.MANAGER_ID = J.EMPLOYEE_ID
)
CYCLE EMPLOYEE_ID SET es_ciclo TO 'Y' DEFAULT 'N'
SELECT LAST_NAME,NIVEL,ES_CICLO
FROM JERARQUIA;

-- FUNCIONES DE GRUPO SOBRE FUNCIONES DE GRUPO - OVER
SELECT DEPARTMENT_ID, SUM (SALARY) AS NOMINA,
    SUM(SUM(SALARY)) OVER() AS NOMINA_TOTAL
FROM HR.EMPLOYEES
GROUP BY DEPARTMENT_ID
HAVING SUM(SALARY) > 10000; --COMPARA SOBRE FUNCIONES DE GRUPO - SELECT, FROM, WHERE, GROUP BY, HAVING - POSICIONES 

             
SELECT  LAST_NAME,
        SALARY,
        SUM(SALARY) OVER (ORDER BY SALARY
                          ROWS BETWEEN UNBOUNDED
                          PRECEDING AND CURRENT ROW) AS ACUM_ROWS,
        SUM(SALARY) OVER (ORDER BY SALARY
                          RANGE BETWEEN UNBOUNDED
                          PRECEDING AND CURRENT ROW) AS ACUM_RANGE
FROM HR.EMPLOYEES
WHERE DEPARTMENT_ID = 90
ORDER BY SALARY;

 